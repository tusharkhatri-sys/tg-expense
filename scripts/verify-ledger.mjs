import assert from 'node:assert/strict';
import { recalculateBalances } from '../src/ledger.ts';
const opening={bank:10000,cash:3000,card:0};
const accounts=[{id:'bank',balance:0,type:'Bank Account'},{id:'cash',balance:0,type:'Cash Wallet'},{id:'card',balance:0,type:'Credit Card'}];
const income={id:'i',type:'Income',amount:5000,from:'bank'};
const expense={id:'e',type:'Expense',amount:1500,from:'bank',to:'cash'};
const transfer={id:'x',type:'Transfer',amount:2000,from:'bank',to:'cash'};
const cardExpense={id:'c',type:'Expense',amount:800,from:'card'};
const result=recalculateBalances(accounts,[income,expense,transfer,cardExpense],opening);
assert.deepEqual(result.map(x=>x.balance),[11500,5000,-800]);
assert.equal(result.reduce((sum,x)=>sum+x.balance,0),15700);
assert.deepEqual(recalculateBalances(accounts,[income,expense,transfer,cardExpense],opening),result,'recalculation must be idempotent');
const edited=recalculateBalances(accounts,[income,{...expense,amount:1700},transfer,cardExpense],opening);
assert.deepEqual(edited.map(x=>x.balance),[11300,5000,-800]);
const deleted=recalculateBalances(accounts,[income,expense,cardExpense],opening);
assert.deepEqual(deleted.map(x=>x.balance),[13500,3000,-800]);
const received=recalculateBalances(accounts,[{id:'g',type:'Received',amount:1200,from:'bank',to:'cash'}],opening);
assert.deepEqual(received.map(x=>x.balance),[11200,3000,0],'Get Money increases only the selected account and is separate from income');
const repayment=recalculateBalances(accounts,[{id:'r',type:'Repayment',amount:500,from:'bank',to:'card'}],opening);
assert.deepEqual(repayment.map(x=>x.balance),[9500,3000,0],'repayments debit the source without crediting a destination account');
console.log('Ledger checks passed: Get Money, expense, transfer, repayment, card spend, edit, delete, idempotency.');
